"""The rental listing table in code says what migration 0039 built.

Alembic's autogenerate does not compare indexes built on an expression, so a
model that disagrees with the database is not caught by it, and a later
autogenerated or hand-written migration could copy the model's version. This
checks the model directly. No database.
"""

from sqlalchemy.dialects import postgresql

from api.src.rental_listings.models import RentalListingRecord


def test_the_case_insensitive_index_is_on_the_unit_column():
    (index,) = [
        index
        for index in RentalListingRecord.__table__.indexes
        if index.name == "uq_rental_listings_unit_lower"
    ]
    (expression,) = index.expressions

    assert index.unique
    assert str(expression.compile(dialect=postgresql.dialect())) == "lower(unit)"
